'use client';

import { useEffect, useMemo, useState } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { api } from '@/lib/api';
import type { CascadeEvent, Plan, Run, RunPolicy, Topology } from '@/types/api';

type View = 'overview' | 'incident' | 'plans' | 'experiments' | 'audit';
const KEY = 'cascade-demo-run-id';
const SEED = 42;
const POLICIES: RunPolicy[] = ['none', 'independent', 'guardrails', 'coordinated'];
const card: React.CSSProperties = { background: 'var(--bg-surface)', border: '1px solid var(--border)', borderRadius: 12, padding: 20 };
const muted: React.CSSProperties = { color: 'var(--text-muted)', fontSize: 13, lineHeight: 1.6 };
const action: React.CSSProperties = { border: 0, borderRadius: 8, background: 'var(--accent)', color: '#fff', padding: '10px 14px', cursor: 'pointer', fontWeight: 600 };

function number(value: number | undefined | null) {
  return typeof value === 'number' ? value.toLocaleString() : '—';
}
function payload(event: CascadeEvent): Record<string, unknown> {
  return event.payload as unknown as Record<string, unknown>;
}

export function BackendDemo({ view, runId }: { view: View; runId?: string }) {
  const router = useRouter();
  const [run, setRun] = useState<Run | null>(null);
  const [topology, setTopology] = useState<Topology | null>(null);
  const [events, setEvents] = useState<CascadeEvent[]>([]);
  const [plans, setPlans] = useState<Plan[]>([]);
  const [comparison, setComparison] = useState<Run[]>([]);
  const [seed, setSeed] = useState(SEED);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => {
    let cancelled = false;
    async function load() {
      try {
        const health = await api.getHealth();
        if (health.status !== 'ok') throw new Error('Sandbox API is not healthy');
        let id = runId ?? localStorage.getItem(KEY);
        let current: Run;
        try {
          current = id ? await api.getRun(id) : await api.createRun({ seed: SEED, scenario: 'db_slowdown', policy: 'coordinated' });
        } catch (reason) {
          if (runId || !(reason instanceof Error) || !reason.message.includes('404')) throw reason;
          current = await api.createRun({ seed: SEED, scenario: 'db_slowdown', policy: 'coordinated' });
        }
        id = current.id;
        if (!runId) localStorage.setItem(KEY, id);
        const [graph, trace, candidates] = await Promise.all([
          api.getTopology(), api.getEvents(id), api.listPlans(id),
        ]);
        if (!cancelled) {
          setRun(current); setTopology(graph); setEvents(trace); setPlans(candidates); setError('');
          window.dispatchEvent(new Event('cascade-run-changed'));
        }
      } catch (reason) {
        if (!cancelled) setError(reason instanceof Error ? reason.message : 'Could not load the sandbox run');
      }
    }
    load();
    return () => { cancelled = true; };
  }, [runId]);

  const decisions = events.filter((event) => event.kind === 'decision');
  const executions = events.filter((event) => event.kind === 'execution');
  const visiblePlans = plans.filter((plan) => plan.actions.length).slice(0, 12);
  const title = { overview: 'Sandbox Overview', incident: 'Incident Replay', plans: 'Recovery Plans', experiments: 'Policy Comparison', audit: 'Event Audit' }[view];
  const explanation = {
    overview: 'One reproducible database slowdown, generated by the backend with a fixed seed.',
    incident: 'The backend replays a simulated incident. Every row below comes from its event stream.',
    plans: 'The coordinator records candidate actions and its predicted risk. Approval verifies a matching replay and updates the plan record.',
    experiments: 'Run all four policies against the same seed. These are in-process simulator outcomes, not production measurements.',
    audit: 'The event log exposes the simulated telemetry, coordinator decisions, and sandbox action records.',
  }[view];

  async function restart() {
    setBusy(true); setError('');
    try {
      const created = await api.createRun({ seed, scenario: 'db_slowdown', policy: 'coordinated' });
      localStorage.setItem(KEY, created.id);
      window.dispatchEvent(new Event('cascade-run-changed'));
      router.push('/incidents/' + created.id);
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : 'Could not create run'); setBusy(false);
    }
  }

  async function approve(plan: Plan) {
    setBusy(true); setError('');
    try {
      await api.approvePlan(plan.id, true);
      setPlans(await api.listPlans(plan.run_id));
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : 'Approval failed');
    } finally { setBusy(false); }
  }

  async function compare() {
    setBusy(true); setError('');
    try {
      const results: Run[] = [];
      for (const policy of POLICIES) {
        results.push(await api.createRun({ seed, scenario: 'db_slowdown', policy }));
      }
      setComparison(results);
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : 'Comparison failed');
    } finally { setBusy(false); }
  }

  const decisionRows = useMemo(() => decisions.filter((e) => (payload(e).actions as string[] | undefined)?.length).slice(0, 12), [decisions]);

  return (
    <main style={{ maxWidth: 1300, display: 'grid', gap: 18 }}>
      <div>
        <h1 style={{ fontSize: 26, color: 'var(--text-primary)', marginBottom: 4 }}>{title}</h1>
        <p style={muted}>{explanation}</p>
      </div>
      <div style={{ ...card, borderColor: 'var(--accent)' }}>
        <strong style={{ color: 'var(--accent)' }}>SIMULATED INFRASTRUCTURE</strong>
        <p style={{ ...muted, marginTop: 8 }}>The API is real and the results come from backend code. The incident, services, and recovery actions run inside a deterministic sandbox. No production infrastructure is connected.</p>
      </div>
      {error && <div role="alert" style={{ ...card, borderColor: 'var(--danger)', color: 'var(--danger)' }}>{error}. Start the backend with <code>python -m backend.api</code> and reload.</div>}
      {!run && !error && <div style={card}>Loading a seeded backend run…</div>}
      {run && (
        <>
          <section style={{ ...card, display: 'flex', gap: 18, alignItems: 'center', flexWrap: 'wrap' }}>
            <div style={{ flex: 1 }}>
              <strong>Run {run.id}</strong>
              <div style={muted}>Seed {run.seed} · {run.scenario} · {run.policy} · {run.state}</div>
            </div>
            <label style={muted}>Seed <input type="number" min="0" value={seed} onChange={(e) => setSeed(Math.max(0, Number(e.target.value) || 0))} style={{ width: 90, padding: 8, marginLeft: 8 }} /></label>
            <button type="button" onClick={restart} disabled={busy} style={action}>Start new sandbox run</button>
          </section>
          {(view === 'overview' || view === 'incident') && (
            <>
              <section style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit,minmax(185px,1fr))', gap: 12 }}>
                {[
                  ['Unique offered', run.metrics?.unique_offered],
                  ['Unique failed', run.metrics?.unique_failed],
                  ['Unique succeeded', run.metrics?.unique_succeeded],
                  ['Peak DB connections', run.metrics?.peak_db_connections],
                  ['Actions in simulation', run.metrics?.actions_executed],
                ].map(([label,value]) => <div key={String(label)} style={card}><div style={muted}>{label}</div><strong style={{ fontSize: 25 }}>{number(value as number)}</strong></div>)}
              </section>
              <section style={{ ...card, display: 'grid', gap: 12 }}>
                <h2 style={{ fontSize: 18 }}>What happened in this run</h2>
                <p style={muted}>The database slows at tick 10. Recovery agents evaluate lagged observable telemetry. The coordinator records selected actions and a heuristic risk estimate. The simulator tracks unique transactions through the end of the run.</p>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10 }}>
                  <Link href={'/plans/' + run.id}>Review candidate plans</Link>
                  <Link href="/experiments">Compare four policies</Link>
                  <Link href="/audit">Inspect event log</Link>
                </div>
              </section>
              <section style={card}>
                <h2 style={{ fontSize: 18, marginBottom: 10 }}>Service topology</h2>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10 }}>
                  {topology?.nodes.map((node) => <div key={node.id} style={{ padding: 12, border: '1px solid var(--border)', borderRadius: 8 }}>{node.id}<div style={muted}>capacity {node.capacity}</div></div>)}
                </div>
                <p style={{ ...muted, marginTop: 10 }}>Dependencies: {topology?.edges.map((edge) => edge.from + ' → ' + edge.to).join(' · ')}</p>
              </section>
              <section style={card}>
                <h2 style={{ fontSize: 18, marginBottom: 10 }}>Coordinator decisions</h2>
                {decisionRows.length ? decisionRows.map((event) => <div key={event.event_id} style={{ borderTop: '1px solid var(--border)', padding: '10px 0' }}>
                  Tick {event.tick}: {(payload(event).actions as string[]).join(', ')} <span style={muted}>· predicted heuristic risk {String(payload(event).predicted_risk)}</span>
                </div>) : <p style={muted}>No action selected in this run.</p>}
                <p style={muted}>{executions.length} action records in the simulator trace. Proposals are evaluated internally but are not emitted as separate events by this API.</p>
              </section>
            </>
          )}
          {view === 'plans' && <section style={card}>
            <h2 style={{ fontSize: 18, marginBottom: 10 }}>Candidate plans with actions</h2>
            <p style={muted}>The run has already been simulated. Approval confirms the candidate against a deterministic replay and marks its record executed. It does not trigger a new infrastructure change.</p>
            {visiblePlans.map((plan) => <div key={plan.id} style={{ borderTop: '1px solid var(--border)', padding: '14px 0', display: 'flex', gap: 16, alignItems: 'center', flexWrap: 'wrap' }}>
              <div style={{ flex: 1 }}><strong>{plan.actions.join(' + ')}</strong><div style={muted}>Risk estimate {plan.predicted_risk} · {plan.reasons.join('; ')} · {plan.status}</div></div>
              {plan.status === 'candidate' && <button type="button" disabled={busy} onClick={() => approve(plan)} style={action}>Approve replay record</button>}
            </div>)}
            {!visiblePlans.length && <p style={muted}>No candidate with an action was generated.</p>}
          </section>}
          {view === 'experiments' && <section style={card}>
            <h2 style={{ fontSize: 18 }}>Same incident, four policies</h2>
            <p style={muted}>Lower unique failed transactions is better. The conventional guardrail is a required baseline.</p>
            <button type="button" disabled={busy} onClick={compare} style={action}>{busy ? 'Running…' : 'Run comparison on this seed'}</button>
            {comparison.length > 0 && <div style={{ overflowX: 'auto', marginTop: 18 }}>
              <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left' }}>
                <thead><tr><th>Policy</th><th>Unique failed</th><th>Actions</th><th>Sustained recovery tick</th></tr></thead>
                <tbody>{comparison.map((arm) => <tr key={arm.id} style={{ borderTop: '1px solid var(--border)' }}>
                  <td style={{ padding: 10 }}>{arm.policy}</td><td>{number(arm.metrics?.unique_failed)}</td><td>{number(arm.metrics?.actions_executed)}</td>
                  <td>{arm.metrics?.sustained_recovery_time === -1 ? 'Not reached' : number(arm.metrics?.sustained_recovery_time)}</td>
                </tr>)}</tbody>
              </table>
              <p style={muted}>One seed is a demonstration, not a statistical result. The 100-seed held-out report found guardrails better than the coordinator.</p>
            </div>}
          </section>}
          {view === 'audit' && <section style={card}>
            <h2 style={{ fontSize: 18 }}>Backend events ({events.length})</h2>
            <p style={muted}>Showing the first 80 events. Each has a simulation tick and provenance.</p>
            <div style={{ maxHeight: 650, overflowY: 'auto' }}>{events.slice(0, 80).map((event) =>
              <details key={event.event_id} style={{ padding: '9px 0', borderTop: '1px solid var(--border)' }}>
                <summary style={{ cursor: 'pointer' }}>Tick {event.tick} · {event.kind} · {event.event_id}</summary>
                <pre style={{ whiteSpace: 'pre-wrap', overflowWrap: 'anywhere', fontSize: 11 }}>{JSON.stringify(event.payload, null, 2)}</pre>
              </details>)}</div>
          </section>}
        </>
      )}
    </main>
  );
}
